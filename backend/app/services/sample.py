def load_sample(session: Session) -> dict:
    """Add the sample words, sets and students. Refuses if the database holds any data."""
    if (
        session.execute(select(func.count()).select_from(models.VocabItem)).scalar_one()
        or session.execute(select(func.count()).select_from(models.Student)).scalar_one()
    ):
        raise bad("Sample data can only be loaded into an empty database")
    drafts = [
        VocabDraft(
            english=english,
            polish=[word.strip() for word in translations.split(",") if word.strip()],
            definition=definition or None,
            part_of_speech=pos or None,
            cefr=cefr or None,
            example=example or None,
            topics=[topic.strip() for topic in topics.split(";") if topic.strip()],
            notes=None,
        )
        for english, translations, definition, pos, cefr, topics, example in ROWS
    ]
    items = create_items(session, drafts)

    def by_topic(topic: str) -> list[str]:
        """Ids of the sample items that have this topic."""
        return [item["id"] for item in items if topic in item["topics"]]

    create_set(session, "Travel Vocabulary", "Airport, hotel and sightseeing", by_topic("Travel"))
    create_set(
        session,
        "A2 Cooking",
        "Kitchen verbs and nouns",
        [item["id"] for item in items if "Cooking" in item["topics"] and item["cefr"] in ("A2", "B1")],
    )
    create_set(session, "Business English", None, by_topic("Business"))
    john = create_student(session, "John Nowak", "B1 · exam in June")
    anna = create_student(session, "Anna Kowalska", "Business focus")
    assign(session, john["id"], by_topic("Cooking") + by_topic("Travel") + by_topic("Emotions"))
    assign(session, anna["id"], by_topic("Business") + by_topic("Money"))
    # The sample shows BANK (money) and BANK (river) as separate meanings on purpose; don't offer them as duplicates.
    by_id = index.items(session)
    for group in duplicates.find_groups([by_id[item["id"]] for item in items], []):
        duplicates.dismiss(session, [item.id for item in group])
    return {"items": len(items), "students": 2}
